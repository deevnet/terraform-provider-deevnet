// A tenant's MQTT account on the platform broker (ADR-0012 §3, §8, §10).
// One account per thing that connects: a device, or a tenant workload.
type iotBrokerAccountResource struct{ client *client.Client }

func NewIoTBrokerAccountResource() resource.Resource { return &iotBrokerAccountResource{} }

type iotBrokerAccountModel struct {
	Tenant   types.String `tfsdk:"tenant"`
	Name     types.String `tfsdk:"name"`
	Device   types.String `tfsdk:"device"`
	Username types.String `tfsdk:"username"`
	// Publish and Subscribe are the tenant's own, RELATIVE patterns.
	Publish   types.List `tfsdk:"publish"`
	Subscribe types.List `tfsdk:"subscribe"`
	// GrantedPublish and GrantedSubscribe are the same patterns as the broker
	// holds them: absolute, with the tenant prefix the API wrote.
	GrantedPublish   types.List   `tfsdk:"granted_publish"`
	GrantedSubscribe types.List   `tfsdk:"granted_subscribe"`
	Password         types.String `tfsdk:"password"`
	Status           types.String `tfsdk:"status"`
	Present          types.Bool   `tfsdk:"present"`
}

func (r *iotBrokerAccountResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_iot_broker_account"
}

